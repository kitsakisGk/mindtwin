"""Experiment E1 (RQ1): end-to-end run of the twin on all C-MAPSS test fleets.

Streams every engine of each test set into a Fleet (staggered starts) and measures throughput
and per-cycle latency in two configurations:

- ``twin``: twins only (validation, state, history)
- ``full``: twins + fleet knowledge graph + live per-condition-normalised trend features
  computed on every cycle (the load the cognition layer will add)

Run from the repository root:

    python experiments/e1/run_e1.py              # writes experiments/results/e1/
    python experiments/e1/run_e1.py --quick      # FD001 only, 1 seed (smoke test)
"""

from __future__ import annotations

import argparse
import json
import platform
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

from mindtwin import __version__
from mindtwin.core.fleet import Fleet
from mindtwin.data.cmapss import SUBSETS, load_cmapss
from mindtwin.data.features import latest_features
from mindtwin.data.preprocessing import ConditionNormalizer, informative_sensors
from mindtwin.data.stream import fleet_stream
from mindtwin.knowledge.graph import KnowledgeGraph

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "experiments" / "results" / "e1"


def environment() -> dict:
    try:
        commit = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True
        ).stdout.strip()
    except OSError:  # pragma: no cover
        commit = "unknown"
    import pandas
    import rdflib

    return {
        "python": sys.version.split()[0],
        "platform": platform.platform(),
        "processor": platform.processor(),
        "mindtwin": __version__,
        "pandas": pandas.__version__,
        "numpy": np.__version__,
        "rdflib": rdflib.__version__,
        "git_commit": commit,
        "timestamp_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }


def run_once(subset: str, config: str, seed: int, stagger: int, window: int) -> dict:
    data = load_cmapss(subset)
    kg = KnowledgeGraph() if config == "full" else None
    base_triples = len(kg) if kg is not None else 0
    fleet = Fleet(knowledge=kg)
    if config == "full":
        sensors = informative_sensors(data.train)
        norm = ConditionNormalizer(sensors).fit(data.train)  # training data only
        fleet.subscribe(lambda twin, snap: latest_features(twin, sensors, window, norm))

    items = list(fleet_stream(data.test, subset, "test", stagger=stagger, seed=seed))
    latencies = np.empty(len(items))
    start = time.perf_counter()
    for i, item in enumerate(items):
        t0 = time.perf_counter_ns()
        fleet.ingest(item.snapshot)
        latencies[i] = (time.perf_counter_ns() - t0) / 1e6  # ms
    wall = time.perf_counter() - start

    return {
        "subset": subset,
        "config": config,
        "seed": seed,
        "engines": len(fleet),
        "cycles": len(items),
        "ticks": items[-1].tick + 1,
        "wall_s": wall,
        "throughput_per_s": len(items) / wall,
        "latency_ms": {
            "p50": float(np.percentile(latencies, 50)),
            "p95": float(np.percentile(latencies, 95)),
            "p99": float(np.percentile(latencies, 99)),
            "max": float(latencies.max()),
        },
        "kg_triples": len(kg) - base_triples if kg is not None else None,
    }


def summarise(runs: list[dict]) -> list[dict]:
    rows = []
    keys = sorted({(r["subset"], r["config"]) for r in runs})
    for subset, config in keys:
        rs = [r for r in runs if r["subset"] == subset and r["config"] == config]
        tp = np.array([r["throughput_per_s"] for r in rs])
        rows.append(
            {
                "subset": subset,
                "config": config,
                "runs": len(rs),
                "engines": rs[0]["engines"],
                "cycles": rs[0]["cycles"],
                "throughput_mean": float(tp.mean()),
                "throughput_std": float(tp.std(ddof=1)) if len(rs) > 1 else 0.0,
                "p50_ms": float(np.mean([r["latency_ms"]["p50"] for r in rs])),
                "p99_ms": float(np.mean([r["latency_ms"]["p99"] for r in rs])),
                "kg_triples": rs[0]["kg_triples"],
            }
        )
    return rows


def markdown(rows: list[dict], env: dict) -> str:
    lines = [
        "# E1 results: end-to-end throughput and latency",
        "",
        f"Commit `{env['git_commit']}`, Python {env['python']}, {env['platform']}, "
        f"{env['processor']}. Generated by `experiments/e1/run_e1.py`.",
        "",
        "| Subset | Config | Runs | Engines | Cycles | Throughput (cycles/s) | p50 latency (ms) "
        "| p99 latency (ms) | KG triples |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        tp = f"{r['throughput_mean']:,.0f}"
        if r["runs"] > 1:
            tp += f" ± {r['throughput_std']:,.0f}"
        kg = f"{r['kg_triples']:,}" if r["kg_triples"] is not None else "-"
        lines.append(
            f"| {r['subset']} | {r['config']} | {r['runs']} | {r['engines']} | {r['cycles']:,} "
            f"| {tp} | {r['p50_ms']:.3f} | {r['p99_ms']:.3f} | {kg} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--subsets", nargs="+", default=list(SUBSETS))
    parser.add_argument("--twin-seeds", type=int, default=3)
    parser.add_argument("--full-seeds", type=int, default=1)
    parser.add_argument("--stagger", type=int, default=100)
    parser.add_argument("--window", type=int, default=10)
    parser.add_argument("--quick", action="store_true", help="FD001, 1 seed each")
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args(argv)
    if args.quick:
        args.subsets, args.twin_seeds, args.full_seeds = ["FD001"], 1, 1

    env = environment()
    runs = []
    for subset in args.subsets:
        for config, n_seeds in (("twin", args.twin_seeds), ("full", args.full_seeds)):
            for seed in range(n_seeds):
                r = run_once(subset, config, seed, args.stagger, args.window)
                print(
                    f"{subset} {config:<4} seed={seed}: {r['cycles']:,} cycles in "
                    f"{r['wall_s']:.1f} s = {r['throughput_per_s']:,.0f}/s, "
                    f"p50 {r['latency_ms']['p50']:.3f} ms, p99 {r['latency_ms']['p99']:.3f} ms",
                    flush=True,
                )
                runs.append(r)

    rows = summarise(runs)
    args.out.mkdir(parents=True, exist_ok=True)
    payload = {"environment": env, "settings": vars(args) | {"out": str(args.out)}, "runs": runs}
    payload["summary"] = rows
    for name, text in (
        ("results.json", json.dumps(payload, indent=2) + "\n"),
        ("results.md", markdown(rows, env)),
    ):
        (args.out / name).write_text(text, encoding="utf-8", newline="\n")
    print(markdown(rows, env))


if __name__ == "__main__":
    main()
